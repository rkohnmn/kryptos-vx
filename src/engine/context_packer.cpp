std::string ContextPacker::extract_structural_skeleton(std::string_view source_code) {
    std::ostringstream oss;
    size_t line_start = 0;
    const size_t n = source_code.size();

    for (size_t i = 0; i <= n; ++i) {
        if (i == n || source_code[i] == '\n') {
            std::string_view line = source_code.substr(line_start, i - line_start);
            // Trim leading spaces
            size_t first_non_space = 0;
            while (first_non_space < line.size() &&
                   (line[first_non_space] == ' ' || line[first_non_space] == '\t')) {
                ++first_non_space;
            }
            std::string_view trimmed = line.substr(first_non_space);

            const bool is_structural =
                trimmed.starts_with("#include") ||
                trimmed.starts_with("#pragma") ||
                trimmed.starts_with("namespace ") ||
                trimmed.starts_with("class ") ||
                trimmed.starts_with("struct ") ||
                trimmed.starts_with("enum ") ||
                trimmed.starts_with("template") ||
                trimmed.starts_with("def ") ||
                trimmed.starts_with("fn ") ||
                trimmed.starts_with("pub fn ") ||
                trimmed.starts_with("export ") ||
                trimmed.starts_with("interface ") ||
                trimmed.starts_with("[[nodiscard]]") ||
                trimmed.starts_with("virtual ") ||
                trimmed.starts_with("static ") ||
                trimmed.starts_with("public:") ||
                trimmed.starts_with("private:") ||
                trimmed.starts_with("protected:");

            if (is_structural) {
                oss << line << "\n";
            }
            line_start = i + 1;
        }
    }
    return oss.str();
}

PackResult ContextPacker::pack_workspace(
    const core::WorkspaceIndexSoA& index,
    const PackConfig& config
) {
    const auto t0 = std::chrono::steady_clock::now();
    PackResult result{};

    // Collect candidate file indices (source & config files, non-binary, non-bloat)
    std::vector<size_t> candidates;
    candidates.reserve(index.size());
    for (size_t i = 0; i < index.size(); ++i) {
        if (index.is_binary[i] != 0) continue;
        if (index.category[i] == core::FileCategory::BuildOrCacheBloat ||
            index.category[i] == core::FileCategory::MediaOrBinary) {
            continue;
        }
        if (config.exclude_tests &&
            (index.relative_path[i].find("test") != std::string_view::npos ||
             index.relative_path[i].find("bench") != std::string_view::npos)) {
            continue;
        }
        candidates.push_back(i);
    }

    // Sort candidates: SourceCode first, then ConfigOrDoc, ordered by path
    std::sort(candidates.begin(), candidates.end(), [&index](size_t a, size_t b) {
        if (index.category[a] != index.category[b]) {
            return static_cast<uint8_t>(index.category[a]) < static_cast<uint8_t>(index.category[b]);
        }
        return index.relative_path[a] < index.relative_path[b];
    });

    std::ostringstream bundle;
    bundle << "# KRYPTOS-VX AI Context Bundle (Vibe-Coding Ready)\n";
    bundle << "> Generated by KRYPTOS-VX C++20 SIMD Context Engine | Token Budget: "
           << config.max_token_budget << " | Secret Scrubbing: "
           << (config.redact_secrets ? "ENABLED" : "DISABLED") << "\n\n";

    bundle << "## Workspace File Tree\n```text\n";
    for (size_t idx : candidates) {
        bundle << index.relative_path[idx] << " (" << index.estimated_tokens[idx] << " tokens)\n";
    }
    bundle << "```\n\n## Repository Contents\n\n";

    for (size_t idx : candidates) {
        const std::string full_p(index.full_path[idx]);
        memory::MappedFile mf(full_p);
        if (!mf.data() || mf.empty()) continue;

        std::string content(mf.view());
        bool was_compressed = false;
        if (config.compress_signatures_only &&
            index.category[idx] == core::FileCategory::SourceCode) {
            std::string skeleton = extract_structural_skeleton(content);
            if (!skeleton.empty()) {
                content = std::move(skeleton);
                was_compressed = true;
            }
        }

        size_t redacted_in_file = 0;
        if (config.redact_secrets) {
            content = core::SimdScanner::redact_secrets(content, &redacted_in_file);
            result.total_secrets_redacted += redacted_in_file;
        }

        const auto metrics = core::SimdScanner::analyze_buffer(
            reinterpret_cast<const uint8_t*>(content.data()),
            content.size()
        );

        if (result.total_tokens + metrics.estimated_tokens > config.max_token_budget) {
            result.skipped_files.emplace_back(index.relative_path[idx]);
            continue;
        }

        result.total_tokens += metrics.estimated_tokens;
        ++result.total_files_packed;

        result.included_files.push_back(PackedFileSummary{
            std::string(index.relative_path[idx]),
            std::string(index.language[idx]),
            index.size_bytes[idx],
            static_cast<uint32_t>(metrics.estimated_tokens),
            was_compressed,
            redacted_in_file
        });

        bundle << "### File: `" << index.relative_path[idx] << "`\n";
        bundle << "- Language: " << index.language[idx]
               << " | Tokens: " << metrics.estimated_tokens
               << " | Lines: " << metrics.total_lines << "\n";
        bundle << "```\n" << content;
        if (!content.empty() && content.back() != '\n') {
            bundle << "\n";
        }
        bundle << "```\n\n";
    }

    result.formatted_bundle = bundle.str();

    if (!config.output_path.empty()) {
        std::ofstream out(config.output_path, std::ios::binary);
        if (out) {
            out.write(result.formatted_bundle.data(),
                      static_cast<std::streamsize>(result.formatted_bundle.size()));
        }
    }

    const auto t1 = std::chrono::steady_clock::now();
    result.pack_duration_ms = std::chrono::duration<double, std::milli>(t1 - t0).count();
    return result;
}

